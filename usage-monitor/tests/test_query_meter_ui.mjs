import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const code = fs.readFileSync(new URL('../assets/query_meter.js', import.meta.url), 'utf8');
const context = vm.createContext({Intl, Set, Number, BigInt});
vm.runInContext(code, context);
const {describe, render} = context.UsageQueryMeter;
const base = {schemaVersion: 1, registeredTurns: 1, coverage: 'turn-start'};
assert.equal(describe(null), null);
assert.equal(describe({...base, status: 'invented'}), null);
assert.equal(describe({...base, status: 'pending'}).value, 'Measuring…');
assert.match(describe({...base, status: 'provisional', subtotal: {totalTokens: 12345}}).value, /12,345 tokens so far/);
assert.match(describe({...base, status: 'provisional', subtotal: {totalTokens: 12345}}).note, /completed response is not yet fully included/);
assert.equal(describe({...base, status: 'complete', final: true, counters: {totalTokens: 12345}}).value, '12,345 tokens');
assert.equal(describe({...base, status: 'complete', final: false, counters: {totalTokens: 12345}}).value, 'Not separately measurable');
assert.equal(describe({...base, status: 'complete', final: true, counters: {totalTokens: -1}}).value, 'Not separately measurable');
assert.equal(describe({...base, status: 'complete', final: true, counters: {totalTokens: 9007199254740992}}).value, 'Not separately measurable');
assert.equal(describe({...base, status: 'complete', final: true, counters: {totalTokens: 9007199254740992}, counterText: {totalTokens: '9007199254740993'}}).value, '9,007,199,254,740,993 tokens');
assert.match(describe({...base, status: 'complete', final: true, counters: {totalTokens: 12}, coverage: 'checkpoint-only'}).note, /Since the start checkpoint/);
assert.equal(describe({...base, status: 'partial', subtotal: {totalTokens: 33}}).value, 'Not separately measurable');
assert.match(describe({...base, status: 'partial', subtotal: {totalTokens: 33}}).note, /Captured-turn subtotal: 33/);
assert.equal(describe({...base, status: 'unavailable'}).value, 'Not separately measurable');
const nodes = new Map(['query-meter', 'query-meter-status', 'query-meter-value', 'query-meter-note'].map(key => [key, {hidden: true, dataset: {}, textContent: ''}]));
const document = {getElementById: key => nodes.get(key)};
render({...base, status: 'complete', final: true, counters: {totalTokens: 100}}, document);
assert.equal(nodes.get('query-meter').hidden, false);
assert.equal(nodes.get('query-meter-value').textContent, '100 tokens');
render(null, document);
assert.equal(nodes.get('query-meter').hidden, true);
console.log('Query measurement UI passed: provisional/final coverage, unavailable scope, exact large integer formatting and safe text rendering.');
